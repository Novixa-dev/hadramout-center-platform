/**
 * Records of the Center's activity transcribed from «عقد من المنجزات والتحديات» (the tenth-anniversary book, printed page in `page`),
 * checked against the page images. Nothing here is inferred: a cell the book leaves empty stays empty.
 *
 * Where the book and the Center's own announcements on the old site disagree, the rule is (docs/client/05-book-vs-site-conflicts-ar.md):
 *  - a date changes only when a second source supports the book (`was` holds the old value, and only that exact value is replaced);
 *  - lecturers come from the announcements, because the lecturer column on printed p. 67 is shifted against its rows
 *    (it contradicts the announcements on 7 of the 8 lectures that can be compared). Rows with no announcement keep no lecturer.
 */
export type BookCollection = 'events' | 'forum_events';
export type BookEventKind = 'conference' | 'seminar' | 'panel' | 'lecture' | 'competition';
/** researcher, title, and an optional note (a prize rank). */
export type BookPaper = readonly [researcher: string, title: string, note?: string];

export interface BookEvent {
  /** Stable identity: array rows are derived from it, so re-running never duplicates anything. */
  key: string;
  collection: BookCollection;
  kind?: BookEventKind;
  /** Part of the title of the row the old site already has. Without it the record is new and uses `title`. */
  match?: string;
  title?: string;
  date?: string;
  end?: string;
  /** The value the old site holds where it is wrong. */
  was?: string;
  /** A year, when the book gives nothing finer. */
  year?: number;
  /** Shown as written when the printed date is incomplete. */
  when?: string;
  venue?: string;
  speaker?: string;
  moderator?: string;
  papers?: readonly BookPaper[];
  researchers?: readonly string[];
  /** Printed page. */
  page: number;
}


const MONTHS = ['يناير', 'فبراير', 'مارس', 'أبريل', 'مايو', 'يونيو', 'يوليو', 'أغسطس', 'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر'];

/** «20–21 ديسمبر 2016م» — the way the book writes its dates. */
export function bookDateText(date: string, end?: string): string {
  const [y, m, d] = date.split('-').map(Number) as [number, number, number];
  const month = MONTHS[m - 1] as string;
  if (!end) return `${d} ${month} ${y}م`;
  const [, em, ed] = end.split('-').map(Number) as [number, number, number];
  return em === m ? `${d}–${ed} ${month} ${y}م` : `${d} ${month} – ${ed} ${MONTHS[em - 1]} ${y}م`;
}
